import {cp,mkdir,mkdtemp,readFile,writeFile,access} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {fileURLToPath} from 'node:url';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {createHash} from 'node:crypto';
import path from 'node:path';
const run=promisify(execFile),here=path.dirname(fileURLToPath(import.meta.url));
const destination=path.resolve(process.argv[2]||path.join(here,'release'));
const version=JSON.parse(await readFile(path.join(here,'package.json'),'utf8')).version;
const name=`ruc802-selfhost-v${version}.tar.gz`,archive=path.join(destination,name);
if(await access(archive).then(()=>true,()=>false))throw new Error('Release already exists; choose a new output directory.');
const checks=JSON.parse(await readFile(path.join(here,'site-checks.json'),'utf8'));
if(!checks.all_passed)throw new Error('Run npm run check before packaging.');
const stage=await mkdtemp(path.join(tmpdir(),'ruc802-release-')),root=path.join(stage,'ruc802');
await mkdir(root);await mkdir(destination,{recursive:true});
const files=['dist','content','deploy','serve.mjs','test-server.mjs','verify-site.mjs','build-data.mjs','build-manifest.json','package-release.mjs','package.json','package-lock.json','Dockerfile','compose.yaml','compose.build.yaml','test-container.mjs','playwright.config.mjs','tests','.dockerignore','.env.example','README.md','DEPLOY.md'];
for(const file of files)await cp(path.join(here,file),path.join(root,file),{recursive:true});
await writeFile(path.join(root,'release.json'),JSON.stringify({version,type:'self-hosted',questions:300,days:50,mathCount:checks.mathCount,runtimeDependencies:[],dataStorage:'browser-local',createdAt:new Date().toISOString()},null,2));
await run('tar',['-czf',archive,'-C',stage,'ruc802'],{windowsHide:true});
const bytes=await readFile(archive),sha256=createHash('sha256').update(bytes).digest('hex');
await writeFile(path.join(destination,'SHA256SUMS'),sha256+'  '+name+'\n');
console.log(JSON.stringify({archive,bytes:bytes.length,sha256,topLevel:'ruc802',stagingDirectory:stage}));
